#!/usr/bin/env bash
#
# check-human-commit.sh — verify that git commits are human-authored.
#
# Detects AI/bot attribution in the author, the committer, and the commit
# message, and fails (exit 1) when any is found. Silent on healthy history.
#
# Usage:
#   scripts/check-human-commit.sh [options] [<rev-or-range>]
#
# Options:
#   --msg-file <file>  Check a raw commit-message file instead of <rev>'s
#                      message. Makes the script usable from a commit-msg hook.
#   --quiet            Suppress output; rely on the exit code only.
#   --version          Print the version and exit.
#   -h, --help         Print this help and exit.
#
# <rev-or-range> defaults to HEAD. A range like <base>..<head> checks every
# commit reachable from <head> but not from <base>, oldest first.
#
# Exit codes:
#   0  every checked commit looks human-authored
#   1  at least one attribution violation
#   2  usage error, not inside a git repository, or unknown revision
#
# License: MIT
set -euo pipefail
LC_ALL=C.UTF-8
export LC_ALL

VERSION="1.1.0"
SCRIPT_NAME="$(basename -- "${BASH_SOURCE[0]}")"
NL=$'\n'

# ---------------------------------------------------------------- colors ----

if [ -t 2 ] && [ -z "${NO_COLOR:-}" ]; then
  RED=$'\e[31m'; GREEN=$'\e[32m'; DIM=$'\e[2m'; RESET=$'\e[0m'
else
  RED=''; GREEN=''; DIM=''; RESET=''
fi

quiet="false"

err()  { printf '%s\n' "${RED}$*${RESET}" >&2; }
ok()   { [ "$quiet" = "true" ] || printf '%s\n' "${GREEN}OK${RESET} $*" >&2; }

# ------------------------------------------------------------------ usage ---

usage() {
  cat <<EOF
$SCRIPT_NAME $VERSION — verify that git commits are human-authored.

Usage: $SCRIPT_NAME [options] [<rev-or-range>]

Options:
  --msg-file <file>  Check a raw commit-message file (for commit-msg hooks).
  --quiet            Suppress output; rely on the exit code only.
  --version          Print the version and exit.
  -h, --help         Print this help and exit.

<rev-or-range> defaults to HEAD; a range such as base..head checks every
commit included in the range.

Exit codes: 0 clean, 1 violation, 2 usage/argument error.
EOF
}

# ---------------------------------------------------------------- parsing ---

rev="HEAD"
msg_file=""

while [ "$#" -gt 0 ]; do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    --version)
      echo "$SCRIPT_NAME version $VERSION"
      exit 0
      ;;
    --quiet|-q)
      quiet="true"
      shift
      ;;
    --msg-file)
      if [ "$#" -lt 2 ] || [ -z "${2:-}" ]; then
        err "$SCRIPT_NAME: --msg-file needs a path"
        exit 2
      fi
      msg_file="$2"
      shift 2
      ;;
    -*)
      err "$SCRIPT_NAME: unknown option: $1"
      usage >&2
      exit 2
      ;;
    *)
      if [ "$rev" != "HEAD" ]; then
        err "$SCRIPT_NAME: multiple revisions given"
        exit 2
      fi
      rev="$1"
      shift
      ;;
  esac
done

# ------------------------------------------------------------ environment ---

if ! git rev-parse --git-dir >/dev/null 2>&1; then
  err "$SCRIPT_NAME: not inside a git repository"
  exit 2
fi

# --------------------------------------------------------------- patterns ---

# Identity tokens that only an assistant or bot would carry.
IDENTITY_AI_RE='(^|[^[:alnum:]])(claude|chatgpt|gpt|copilot|gemini|opencode|cursor-agent|aider|codex|anthropic|openai|bot|assistant)([^[:alnum:]]|$)'

# Message patterns, applied per line, case-insensitive.
MESSAGE_RES=(
  'co-authored-by:[[:space:]].*(claude|chatgpt|gpt|copilot|gemini|opencode|cursor|aider|codex|anthropic|openai|bot|assistant)'
  '(anthropic\.com|openai\.com|claude\.ai|chatgpt\.com|opencode\.ai|cursor\.sh|aider\.chat)'
  '(generated|made|built|created|assisted|co-written|powered) (with|by|using) (claude|chatgpt|gpt|copilot|gemini|opencode|cursor|aider|codex|an ai|a ai)'
  'ai-generated|ai generated|auto-generated by ai'
)
# Robot emoji, matched as literal bytes so it works in any locale.
EMOJI_RE='🤖'

declare -A VIOLATIONS_BY_COMMIT=()

check_commit() {
  # $1 = commit label; $2 = message; $3 = author; $4 = committer.
  local label="$1" message="$2" author="$3" committer="$4"
  local -a hits=()
  local pair kind value re line hit seen

  for pair in "author=$author" "committer=$committer"; do
    kind="${pair%%=*}"
    value="${pair#*=}"
    case "$value" in
      '(not checked: --msg-file)') continue ;;
    esac
    if [ -z "${value// /}" ]; then
      hits+=("    $kind identity is empty")
    elif printf '%s\n' "$value" | grep -Eqi "$IDENTITY_AI_RE"; then
      hits+=("    $kind identity looks like an AI or bot: $value")
    fi
  done

  for re in "${MESSAGE_RES[@]}" "$EMOJI_RE"; do
    while IFS= read -r hit; do
      [ -n "$hit" ] || continue
      if [[ "$hit" == *"🤖"* ]]; then
        line="    message contains robot emoji: $hit"
      else
        line="    message contains forbidden attribution: $hit"
      fi
      # The same line can match several patterns; report it once.
      seen=""
      for h in "${hits[@]}"; do
        [ "$h" = "$line" ] && seen="1"
      done
      [ -n "$seen" ] || hits+=("$line")
    done < <(printf '%s' "$message" | grep -Ei "$re" || true)
  done

  if [ "${#hits[@]}" -gt 0 ]; then
    VIOLATIONS_BY_COMMIT["$label"]="$(printf '%s\n' "${hits[@]}")$NL"
    return 1
  fi
  return 0
}

# ---------------------------------------------------------- message mode ---

if [ -n "$msg_file" ]; then
  if [ ! -f "$msg_file" ]; then
    err "$SCRIPT_NAME: message file not found: $msg_file"
    exit 2
  fi
  if ! check_commit "message file: $msg_file" "$(cat "$msg_file")" \
      "(not checked: --msg-file)" "(not checked: --msg-file)"; then
    err "check: FAILED — the message carries AI or bot attribution:"
    printf '%s\n' "${VIOLATIONS_BY_COMMIT["message file: $msg_file"]}" >&2
    exit 1
  fi
  ok "— message is clean"
  exit 0
fi

# ------------------------------------------------------------ rev checks ---

commits=()

if [[ "$rev" == *..* ]]; then
  if ! commit_list="$(git rev-list --reverse "$rev" 2>/dev/null)"; then
    err "$SCRIPT_NAME: unknown revision range: $rev"
    exit 2
  fi
  while IFS= read -r c; do
    [ -n "$c" ] || continue
    commits+=("$c")
  done <<< "$commit_list"
  if [ "${#commits[@]}" -eq 0 ]; then
    ok "— range $rev is empty"
    exit 0
  fi
else
  if ! git rev-parse --verify --quiet "${rev}^{commit}" >/dev/null 2>&1; then
    err "$SCRIPT_NAME: unknown revision: $rev"
    exit 2
  fi
  commits+=("$(git rev-parse --verify "$rev^{commit}")")
fi

# ----------------------------------------------------------------- report ---

failed=0
for c in "${commits[@]}"; do
  check_commit "$c" \
    "$(git log -1 --format='%B' "$c")" \
    "$(git log -1 --format='%an <%ae>' "$c")" \
    "$(git log -1 --format='%cn <%ce>' "$c")" || failed=$((failed + 1))
done

if [ "$failed" -gt 0 ]; then
  err "check: FAILED — $failed of ${#commits[@]} commit(s) in $rev carry AI or bot attribution:"
  for c in $(printf '%s\n' "${!VIOLATIONS_BY_COMMIT[@]}" | sort); do
    printf '  %s%s%s\n' "$DIM" "$(git log -1 --format='%h %s' "$c")" "$RESET" >&2
    printf '%s\n' "${VIOLATIONS_BY_COMMIT[$c]}" >&2
  done
  exit 1
fi

ok "— ${#commits[@]} commit(s) in $rev are authored and committed as humans"
exit 0
