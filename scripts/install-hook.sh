#!/usr/bin/env bash
#
# install-hook.sh — install a commit-msg hook that blocks AI-attributed commits.
#
# The hook calls check-human-commit.sh --msg-file, so every commit in this
# repository is rejected at commit time if it carries AI or bot attribution.
#
# Usage:
#   scripts/install-hook.sh [--remove] [--dry-run]
#
#   --remove   Remove the hook (restores a pre-existing backup if one exists).
#   --dry-run  Print the hook that would be written, change nothing.
#
# Exit codes: 0 success, 1 environment error, 2 usage error.
#
# License: MIT
set -euo pipefail
LC_ALL=C.UTF-8
export LC_ALL

VERSION="1.1.0"
SCRIPT_NAME="$(basename -- "${BASH_SOURCE[0]}")"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
HOOK_NAME="commit-msg"
MARKER="installed by human-commit"

usage() {
  cat <<EOF
$SCRIPT_NAME $VERSION — install or remove the human-commit $HOOK_NAME hook.

Usage: $SCRIPT_NAME [--remove] [--dry-run]

Options:
  --remove   Remove the hook, restoring a backup if one was saved.
  --dry-run  Print what would be written; change nothing.
  -h, --help Print this help and exit.
EOF
}

dry_run="false"
mode="install"

while [ "$#" -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --remove) mode="remove"; shift ;;
    --dry-run) dry_run="true"; shift ;;
    *) echo "$SCRIPT_NAME: unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if ! command -v git >/dev/null 2>&1; then
  echo "$SCRIPT_NAME: git not found in PATH" >&2
  exit 1
fi

git_dir="$(git rev-parse --git-dir 2>/dev/null)" || {
  echo "$SCRIPT_NAME: not inside a git repository" >&2
  exit 1
}
git_dir="$(cd -- "$git_dir" && pwd)"
hooks_dir="$git_dir/hooks"

if git config --get core.hooksPath >/dev/null 2>&1; then
  hooks_dir="$(git config --get core.hooksPath)"
  case "$hooks_dir" in
    /*) ;;
    *) hooks_dir="$(git rev-parse --show-toplevel)/$hooks_dir" ;;
  esac
fi

hook_path="$hooks_dir/$HOOK_NAME"
backup_path="$hook_path.human-commit-backup"
checker="$SCRIPT_DIR/check-human-commit.sh"

hook_content="$(
  cat <<EOF
#!/usr/bin/env bash
# $MARKER v$VERSION — reject commits with AI or bot attribution.
# Generated by install-hook.sh; the checker lives beside it and is not copied.
CHECKER="$checker"

exec "\$CHECKER" --msg-file "\$1"
EOF
)"

if [ "$mode" = "remove" ]; then
  if [ "$dry_run" = "true" ]; then
    echo "would remove $hook_path (backup restored if present)"
    exit 0
  fi
  if [ -f "$hook_path" ] && grep -q "$MARKER" "$hook_path" 2>/dev/null; then
    rm -- "$hook_path"
    echo "removed $hook_path"
  else
    echo "$SCRIPT_NAME: no hook at $hook_path — nothing to remove" >&2
  fi
  if [ -f "$backup_path" ]; then
    mv -- "$backup_path" "$hook_path"
    echo "restored pre-existing hook from $backup_path"
  fi
  exit 0
fi

if [ "$dry_run" = "true" ]; then
  echo "would write $hook_path with:"
  printf '%s\n' "$hook_content"
  exit 0
fi

if [ ! -x "$checker" ]; then
  echo "$SCRIPT_NAME: checker missing or not executable: $checker" >&2
  exit 1
fi

mkdir -p -- "$hooks_dir"

if [ -e "$hook_path" ] && ! grep -q "$MARKER" "$hook_path" 2>/dev/null; then
  if [ -e "$backup_path" ]; then
    echo "$SCRIPT_NAME: refusing to overwrite existing $hook_path; backup already exists at $backup_path" >&2
    exit 1
  fi
  mv -- "$hook_path" "$backup_path"
  echo "existing hook saved as $backup_path"
fi

printf '%s\n' "$hook_content" > "$hook_path"
chmod +x "$hook_path"
echo "installed $hook_path"
